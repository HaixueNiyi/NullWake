enum class AppLanguage(val key: String) {
    SYSTEM("system"),
    ZH_TW("zh_tw"),
    EN("en");

    companion object {
        fun fromKey(key: String?): AppLanguage =
            entries.firstOrNull { it.key == key } ?: SYSTEM
    }
}

